def kop(s, season=None):
    if not s:
        return ''
    if (season, s) in KOPECKS_READ:
        return KOPECKS_READ[(season, s)]
    m = re.fullmatch(r'([\d,]+) р\. (\d+|—) к\.?', s)
    if not m:
        sys.exit(f'unparseable receipts: {s!r}')
    return int(m.group(1).replace(',', '')) * 100 + (0 if m.group(2) == '—' else int(m.group(2)))


def main():
    order = {s: i for i, s in enumerate(sorted(PAGES))}
    lines, n = [], {}
    for r in sorted(LINES, key=lambda r: order[r[0]]):
        n[r[0]] = n.get(r[0], 0) + 1
        lines.append((r[0], r[1], n[r[0]], *r[2:9], kop(r[8], r[0]), r[9], r[10]))
    problems = 0
    # subtotal == sum of the venue lines of the same season/city/category
    for s in PAGES:
        rows = [r for r in lines if r[0] == s]
        for i, r in enumerate(rows):
            if r[3] != 'subtotal':
                continue
            parts = [x for x in rows[:i] if x[3] in ('venue', 'part') and x[5] == r[5] and x[1] == r[1]]
            c, k = sum(x[8] for x in parts), sum(x[10] or 0 for x in parts)
            bad = c != r[8] or (r[10] != '' and k != r[10])
            if bad and not r[12].startswith('PRINT:'):
                print(f'UNFLAGGED MISMATCH {s} {r[1]} {r[5]}: count {r[8]} vs {c}, kop {r[10]} vs {k}'); problems += 1
            if not bad and r[12].startswith('PRINT:') and 'KOPECKS_READ' not in r[12]:
                print(f'FLAGGED BUT ADDS UP {s} {r[1]} {r[5]}'); problems += 1
    # footnote refs must exist
    fn = {(f[0], f[1]) for f in FOOTNOTES}
    for r in lines:
        for ref in filter(None, r[11].split(',')):
            if (r[0], int(ref)) not in fn:
                print(f'MISSING FOOTNOTE {r[0]} {ref}'); problems += 1
    # mixed-script words
    for row in [*lines, *FOOTNOTES, *[(s, *v) for s, v in PAGES.items()]]:
        for v in row:
            for w in re.findall(r'\w+', str(v)):
                if re.search('[a-zA-Z]', w) and re.search('[а-яА-ЯѣѢіІѳъ]', w):
                    print(f'MIXED SCRIPT {row[0]}: {w}'); problems += 1
    def write(name, hdr, rows):
        with open(HERE / name, 'w', newline='', encoding='utf-8') as f:
            w = csv.writer(f); w.writerow(hdr); w.writerows(rows)
    write('pages.csv', ['season', 'source_file', 'printed_page', 'heading_verbatim', 'heading_footnote', 'format', 'note'],
          [(s, *PAGES[s]) for s in sorted(PAGES)])
    write('lines.csv', ['season', 'city', 'line_no', 'line_kind', 'category_verbatim', 'category', 'venue_verbatim',
                        'qualifier_verbatim', 'count', 'receipts_verbatim', 'receipts_kopecks', 'footnote_refs', 'note'], lines)
    write('footnotes.csv', ['season', 'footnote_no', 'text_verbatim', 'note'], sorted(FOOTNOTES, key=lambda f: (order[f[0]], f[1])))
    print(f'{len(PAGES)} pages, {len(lines)} lines, {len(FOOTNOTES)} footnotes; problems: {problems}')
    sys.exit(1 if problems else 0)


if __name__ == '__main__':
    main()
