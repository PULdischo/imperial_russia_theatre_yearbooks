"""One-off builder script for the Spiski (roster) gold-standard CSVs.
Not part of the extraction pipeline -- used to safely emit CSV from
hand-transcribed Python data structures."""
import csv
from pathlib import Path

OUT = Path(__file__).parent

entries = []
periods = []
credits = []

_entry_n = {}


def add_entry(page_id, entity_type, institution, department, position, list_number,
              family_name, first_name="", patronymic="", rank_or_title="",
              service_class="", instrument="", subject_taught="",
              tenure_note_text="", credit_summary_text="",
              periods_list=None, credits_list=None):
    # department/position collapsed into one verbatim heading_path column
    # (see docs/schema.md) -- kept as two call-site args here purely so the
    # ~140 hand-transcribed add_entry(...) calls below didn't need editing.
    heading_path = " / ".join(p for p in (department, position) if p)
    _entry_n[page_id] = _entry_n.get(page_id, 0) + 1
    entry_id = f"{page_id}__e{_entry_n[page_id]:03d}"
    entries.append(dict(
        entry_id=entry_id, page_id=page_id, entity_type=entity_type,
        institution=institution, heading_path=heading_path,
        list_number=list_number, family_name=family_name, first_name=first_name,
        patronymic=patronymic, rank_or_title=rank_or_title, service_class=service_class,
        instrument=instrument, subject_taught=subject_taught,
        tenure_note_text=tenure_note_text, credit_summary_text=credit_summary_text,
    ))
    for i, p in enumerate(periods_list or [], start=1):
        start_text, start_undate, end_text, end_undate, end_type = p
        periods.append(dict(period_id=f"{entry_id}__sp{i}", entry_id=entry_id, period_order=i,
                             start_date_text=start_text, start_date_undate=start_undate,
                             end_date_text=end_text, end_date_undate=end_undate, end_type=end_type))
    for i, c in enumerate(credits_list or [], start=1):
        credit_type, label, role_name, count = c
        credits.append(dict(credit_id=f"{entry_id}__cr{i}", entry_id=entry_id,
                             credit_type=credit_type, label=label, role_name=role_name, count=count))
    return entry_id


