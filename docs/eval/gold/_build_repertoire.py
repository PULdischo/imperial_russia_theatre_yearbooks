"""One-off builder script for the repertoire gold-standard CSVs.
Not part of the extraction pipeline -- just used to safely emit CSV from
hand-transcribed Python data structures (avoids manual CSV-quoting mistakes
with Cyrillic text that contains commas)."""
import csv
from pathlib import Path

OUT = Path(__file__).parent

sessions = []
works = []


def add_session(session_id, page_id, season, city, date_text, month_text, year_text,
                 date_undate, session, theater, is_dark, receipts_text="", annotation="",
                 work_list=None):
    rub, kop = "", ""
    if receipts_text:
        # verbatim text like "3462 р. 15 к." or "1321 р. -- к."
        try:
            parts = receipts_text.replace("—", "-").split("р.")
            rub = parts[0].strip()
            kop_part = parts[1].replace("к.", "").strip()
            kop = kop_part if kop_part != "-" else ""
        except Exception:
            pass
    sessions.append(dict(
        session_id=session_id, page_id=page_id, season=season, city=city,
        date_text=date_text, month_text=month_text, year_text=year_text,
        date_undate=date_undate, session=session, theater=theater,
        is_dark=is_dark, receipts_text=receipts_text,
        receipts_rubles=rub, receipts_kopecks=kop, annotation=annotation,
    ))
    if work_list:
        for i, (title, genre) in enumerate(work_list, start=1):
            works.append(dict(work_id=f"{session_id}__w{i}", session_id=session_id,
                               work_order=i, work_title=title, genre=genre))


